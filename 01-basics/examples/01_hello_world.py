"""Example 01 – Different ways to use print()."""

print("Hello, world!")
print("Python", "is", "fun")
print("2026", "10", "19", sep="-")
print("Loading", end="")
print("...", end="")
print(" done!")

# Printing an empty line
print()

# Escape characters
print("Line one\nLine two")       # \n = new line
print("Name:\tAda")               # \t = tab
print("She said \"hi\"")          # \" = a quote inside a string
print('It\'s easy')
